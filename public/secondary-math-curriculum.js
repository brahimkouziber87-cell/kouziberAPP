    /**
     * تطبيع عنوان الدرس للمقارنة اللينة
     */
    function normTitle(t) {
        if (!t) return '';
        return String(t)
            .toLowerCase()
            .replace(/[أإآ]/g, 'ا')
            .replace(/ة/g, 'ه')
            .replace(/[\u064B-\u065F]/g, '')
            .replace(/[\-_:,\.؛\(\)]/g, ' ')
            .replace(/\s+/g, ' ')
            .trim();
    }

    /**
     * جلب المحاور المحددة في المقرر والتوزيع السنوي لدرس معين
     */
    function getCurriculumPlannedAxes(className, lessonTitle) {
        if (!lessonTitle) return null;
        const normKey = normTitle(lessonTitle);
        const preferredLevel = getCurriculumLevelForClass(className);

        // 1. Search in preferred level first
        const levelData = MOROCCAN_SECONDARY_MATH_CURRICULUM[preferredLevel];
        if (levelData && levelData.semesters) {
            for (const semKey of ['s1', 's2']) {
                const lessons = levelData.semesters[semKey]?.lessons || [];
                for (const l of lessons) {
                    const lNorm = normTitle(l.title);
                    if (normKey.includes(lNorm) || lNorm.includes(normKey)) {
                        return l.axes.map(ax => ax.title);
                    }
                }
            }
        }

        // 2. Search in all levels if not matched in preferred
        for (const [lvlKey, lvlObj] of Object.entries(MOROCCAN_SECONDARY_MATH_CURRICULUM)) {
            if (lvlKey === preferredLevel) continue;
            for (const semKey of ['s1', 's2']) {
                const lessons = lvlObj.semesters?.[semKey]?.lessons || [];
                for (const l of lessons) {
                    const lNorm = normTitle(l.title);
                    if (normKey.includes(lNorm) || lNorm.includes(normKey)) {
                        return l.axes.map(ax => ax.title);
                    }
                }
            }
        }

        return null;
    }
