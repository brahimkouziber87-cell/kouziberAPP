    window.linkCurriculumLessonToLessonLog = function(targetClass, encodedTitle, encodedAxes) {
        try {
            const title = decodeURIComponent(encodedTitle);
            const axes = JSON.parse(decodeURIComponent(encodedAxes));

            // Switch to lesson log tab
            if (typeof window.switchTab === 'function') {
                window.switchTab('lessonlog');
            }

            // Set class
            const classSelect = document.getElementById('lessonLogClassSelect');
            if (classSelect) {
                if (targetClass && Array.from(classSelect.options).some(o => o.value === targetClass)) {
                    classSelect.value = targetClass;
                }
                if (typeof window.renderLessonLogs === 'function') {
                    window.renderLessonLogs();
                }
            }

            // Populate form
            const lessonTitleInput = document.getElementById('lessonLogNumber');
            if (lessonTitleInput) {
                lessonTitleInput.value = title;
            }

            const titleHiddenInput = document.getElementById('lessonLogTitle');
            if (titleHiddenInput) {
                titleHiddenInput.value = title;
            }

            // Prefill axes
            if (typeof window.setLessonLogAxesFields === 'function' && Array.isArray(axes)) {
                const preparedAxes = axes.map((ax) => ({
                    title: ax.title,
                    color: '#ffffff',
                    paragraphs: ax.desc ? [{ title: 'بناء المفهوم والتطبيقات', content: ax.desc, type: 'construct' }] : []
                }));
                window.setLessonLogAxesFields(preparedAxes);
            }

            // Focus on form
            const formCard = document.getElementById('lessonLogFormCard');
            if (formCard) {
                formCard.scrollIntoView({ behavior: 'smooth', block: 'start' });
            }

            if (typeof window.showToast === 'function') {
                window.showToast(`✅ تم بنجاح جلب وتعبئة درس [${title}] ومحاوره من التوزيع السنوي الوزاري`, 'success');
            }
        } catch (e) {
            console.error('Error linking curriculum to lesson log', e);
            if (typeof window.showToast === 'function') {
                window.showToast('حدث خطأ أثناء ربط الدرس بدفتر النصوص', 'error');
            }
        }
    };

